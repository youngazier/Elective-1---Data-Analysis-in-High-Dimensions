S <- c(S1="ABCAD",S2="ABCAE",S3="ABDAD",S4="CEFBA",S5="CEFBB",S6="DEFBA")
m <- do.call(rbind, strsplit(S,""))
D <- outer(1:6,1:6,Vectorize(function(i,j) mean(m[i,]!=m[j,])))
dimnames(D) <- list(names(S),names(S)); print(D)
png("output/figures/diag03_hamming_matrix.png",width=1000,height=880,res=180)
par(mar=c(4,4,3,1))
image(1:6,1:6,D[,6:1],col=colorRampPalette(c("white","#08519c"))(50),zlim=c(0,1),axes=FALSE,xlab="",ylab="",main="Hamming distance matrix (6 example students)")
axis(1,1:6,names(S));axis(2,1:6,rev(names(S)),las=1)
for(i in 1:6)for(j in 1:6)text(j,7-i,sprintf("%.1f",D[i,j]),col=if(D[i,j]>.6)"white" else "black")
box();dev.off()

h <- hclust(as.dist(D), method="average")
print(h$merge); print(h$height)
png("output/figures/diag04_hamming_dendrogram.png",width=1100,height=880,res=180)
par(mar=c(3,4,3,1))
plot(h,hang=-1,main="Dendrogram of the 6 example students (average linkage)",xlab="",sub="",ylab="Merge height (Hamming distance)",ylim=c(0,1))
rect.hclust(h,k=2,border=c("#f58220","#08519c"))
abline(h=0.6,lty=2,col="red");text(0.7,0.63,"cut -> K = 2",col="red",pos=4)
dev.off()
